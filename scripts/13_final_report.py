"""Stage 13: the TASK.md results tables from the final evaluation (stage 12) of seeds 0-4.

Reads `artifacts/final/seed_<s>/results.json` and writes `docs/results.md` and
`artifacts/final/summary.csv`. Reports test macro AUROC and balanced accuracy as mean ± sd over
the seeds and, per seed, 95% bootstrap CIs over the seed's test patients; the paired fused-vs-row
comparisons; per-class AUROC; the confusion matrix summed over the test sets; development vs test;
the metadata diagnostic; the D11 sensitivity analysis.

Usage: uv run --no-sync python -m scripts.13_final_report [--dir artifacts/final] [--out docs/results.md]
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
import pandas as pd

from src.data.cohort import CLASSES
from src.utils.config import load_config

NAMES = {"meta": "Metadata only (age + sex)", "uni2h": "UNI2-h alone", "virchow2": "Virchow2 alone",
         "genbio_pathfm": "GenBio-PathFM alone", "best_plus_meta": "Best single model + metadata",
         "fused": "**Fused (agent-selected) + metadata**", "no_meta": "Fused without metadata (diagnostic)"}
BASE = {"metadata": "Metadata only (age + sex)", "uni2h": "UNI2-h alone", "virchow2": "Virchow2 alone",
        "genbio_pathfm": "GenBio-PathFM alone", "best_single_plus_metadata": "Best single model + metadata"}
MODEL = {"uni2h": "UNI2-h", "virchow2": "Virchow2", "genbio_pathfm": "GenBio-PathFM"}
TABLE_ROWS = ["meta", "uni2h", "virchow2", "genbio_pathfm", "best_plus_meta", "fused"]


def ms(v: list[float]) -> str:
    return f"{np.mean(v):.3f} ± {np.std(v, ddof=1):.3f}" if len(v) > 1 else f"{v[0]:.3f}"


def ci(s: dict, m: str) -> str:
    return f"{s[m]['estimate']:.3f} [{s[m]['ci'][0]:.3f}, {s[m]['ci'][1]:.3f}]"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--dir", type=Path, default=Path("artifacts/final"))
    ap.add_argument("--out", type=Path, default=Path("docs/results.md"))
    ap.add_argument("--config", type=Path, default=Path("conf/final.yaml"))
    args = ap.parse_args()
    fcfg = load_config(args.config)
    runs = {int(p.parent.name.split("_")[1]): json.loads(p.read_text())
            for p in sorted(args.dir.glob("seed_*/results.json"))}
    if not runs:
        raise SystemExit(f"no results in {args.dir}")
    seeds = sorted(runs)
    missing = sorted(set(fcfg["seeds"]) - set(seeds))
    primary = next(k for k, d in fcfg["designs"].items() if d["role"] == "primary")
    L: list[str] = []
    w = L.append
    rows_csv = []

    w("# Results: final evaluation on the held-out test sets\n")
    w(f"Seeds {', '.join(map(str, seeds))}" + (f" (missing: {missing})" if missing else "") +
      f"; per seed 162 development and 41 test patients, disjoint by patient. Code: "
      f"{', '.join(sorted({r['code'][:10] for r in runs.values()}))}. GPU: "
      f"{', '.join(sorted({r['device'] for r in runs.values()}))}. Generated by `scripts/13_final_report.py` "
      f"from `{args.dir}/seed_*/results.json`.\n")
    w("**Protocol.** The designs, the primary design, the rows and the claim rule were frozen in "
      "`conf/final.yaml` before any test set was read (decisions/SUMMARY.md). Per seed, each model is "
      "fitted once on all 162 development patients and predicts the 41 test patients once. "
      "Uncertainty: mean ± sd over the seeds, and per seed a 95% bootstrap CI over its test patients "
      "(2,000 class-stratified resamples). Every row under a design uses that design's own recipe "
      "(TASK.md §5.3: identical classifier family and budget); the original rows 1–5 (mean-pooled "
      "slide vectors + tuned logistic regression) are shown as a separate reference. Seed 0 is the "
      "headline split; seeds 1–4 are secondary (their development sets overlap seed 0's test set, "
      "on which the designs were not selected but whose development data guided the loop).\n")

    for design, d in fcfg["designs"].items():
        res = {s: runs[s]["designs"][design] for s in seeds}
        role = "primary, agent-selected" if design == primary else "secondary"
        w(f"## {design} ({d['candidate']}, {role}): TASK.md §5.3 table\n")
        w("| Configuration | Test macro AUROC (mean ± sd) | Test balanced acc. (mean ± sd) | Seed 0 test AUROC [95% CI] | "
          "Seed 0 test bal. acc. [95% CI] | Dev AUROC (mean ± sd) |")
        w("| --- | --- | --- | --- | --- | --- |")
        for row in TABLE_ROWS + ["no_meta"]:
            ta = [res[s]["rows"][row]["test"]["macro_auroc"]["estimate"] for s in seeds]
            tb = [res[s]["rows"][row]["test"]["balanced_accuracy"]["estimate"] for s in seeds]
            da = [res[s]["rows"][row]["dev"]["macro_auroc"]["estimate"] for s in seeds]
            name = NAMES[row]
            if row == "best_plus_meta":
                picks = [MODEL[res[s]["rows"][row]["model"]] for s in seeds]
                name += f" ({', '.join(f'{p}' for p in picks)})"
            if row == "fused" and design != primary:
                name = "**Fused + metadata**"
            s0 = res[0]["rows"][row]["test"] if 0 in res else None
            w(f"| {name} | {ms(ta)} | {ms(tb)} | {ci(s0, 'macro_auroc') if s0 else '–'} | "
              f"{ci(s0, 'balanced_accuracy') if s0 else '–'} | {ms(da)} |")
            for s in seeds:
                r = res[s]["rows"][row]
                rows_csv.append({"design": design, "row": row, "seed": s,
                                 "test_auroc": r["test"]["macro_auroc"]["estimate"],
                                 "test_auroc_ci_low": r["test"]["macro_auroc"]["ci"][0],
                                 "test_auroc_ci_high": r["test"]["macro_auroc"]["ci"][1],
                                 "test_bacc": r["test"]["balanced_accuracy"]["estimate"],
                                 "test_bacc_ci_low": r["test"]["balanced_accuracy"]["ci"][0],
                                 "test_bacc_ci_high": r["test"]["balanced_accuracy"]["ci"][1],
                                 "dev_auroc": r["dev"]["macro_auroc"]["estimate"],
                                 "dev_bacc": r["dev"]["balanced_accuracy"]["estimate"]})
        w("")

        # Does fusion beat every single model? Paired, per seed, on the test set.
        w(f"**{design}: fused vs each row on the test set** (paired bootstrap over the test patients; gain in "
          "macro AUROC [95% CI], share of resamples won). A row is beaten on a seed when the CI excludes 0.\n")
        w("| Fused vs | " + " | ".join(f"Seed {s}" for s in seeds) + " | Mean gain ± sd | Seeds gain > 0 | Seeds CI > 0 |")
        w("| --- | " + " | ".join("---" for _ in seeds) + " | --- | --- | --- |")
        for row in ["uni2h", "virchow2", "genbio_pathfm", "best_plus_meta", "meta", "no_meta"]:
            cs = [res[s]["fused_vs_row_on_test"][row] for s in seeds]
            cells = [f"{c['gain']:+.3f} [{c['ci'][0]:+.3f}, {c['ci'][1]:+.3f}], {100 * c['share_won']:.0f}%" for c in cs]
            g = [c["gain"] for c in cs]
            w(f"| {NAMES[row].replace('**', '')} | " + " | ".join(cells) +
              f" | {np.mean(g):+.3f} ± {np.std(g, ddof=1) if len(g) > 1 else 0:.3f} | "
              f"{sum(x > 0 for x in g)}/{len(g)} | {sum(c['ci'][0] > 0 for c in cs)}/{len(cs)} |")
        w("")

    # The original rows 1-5 (stage 09) on the same test sets, and each design's fused model against them.
    w("## Reference: the original rows 1–5 (mean-pooled slide vectors + tuned logistic regression)\n")
    w("| Configuration | Test macro AUROC (mean ± sd) | Test balanced acc. (mean ± sd) | Seed 0 test AUROC [95% CI] | "
      "Seed 0 test bal. acc. [95% CI] | Dev AUROC (mean ± sd) |")
    w("| --- | --- | --- | --- | --- | --- |")
    for row, name in BASE.items():
        b = {s: runs[s]["baselines"][row] for s in seeds}
        if row == "best_single_plus_metadata":
            name += f" ({', '.join(MODEL[b[s]['model']] for s in seeds)})"
        s0 = b[0]["test"] if 0 in b else None
        w(f"| {name} | {ms([b[s]['test']['macro_auroc']['estimate'] for s in seeds])} | "
          f"{ms([b[s]['test']['balanced_accuracy']['estimate'] for s in seeds])} | "
          f"{ci(s0, 'macro_auroc') if s0 else '–'} | {ci(s0, 'balanced_accuracy') if s0 else '–'} | "
          f"{ms([b[s]['dev']['macro_auroc']['estimate'] for s in seeds])} |")
        for s in seeds:
            r = b[s]
            rows_csv.append({"design": "baseline", "row": row, "seed": s,
                             "test_auroc": r["test"]["macro_auroc"]["estimate"],
                             "test_auroc_ci_low": r["test"]["macro_auroc"]["ci"][0],
                             "test_auroc_ci_high": r["test"]["macro_auroc"]["ci"][1],
                             "test_bacc": r["test"]["balanced_accuracy"]["estimate"],
                             "test_bacc_ci_low": r["test"]["balanced_accuracy"]["ci"][0],
                             "test_bacc_ci_high": r["test"]["balanced_accuracy"]["ci"][1],
                             "dev_auroc": r["dev"]["macro_auroc"]["estimate"],
                             "dev_bacc": r["dev"]["balanced_accuracy"]["estimate"]})
    w("")
    w("**Each design's fused model vs the original rows** (test AUROC gain, mean ± sd over seeds; seeds with "
      "the paired CI above 0).\n")
    w("| Design | " + " | ".join(BASE.values()) + " |")
    w("| --- | " + " | ".join("---" for _ in BASE) + " |")
    for design in fcfg["designs"]:
        cells = []
        for row in BASE:
            cs = [runs[s]["designs"][design]["fused_vs_baseline_on_test"][row] for s in seeds]
            g = [c["gain"] for c in cs]
            cells.append(f"{np.mean(g):+.3f} ± {np.std(g, ddof=1) if len(g) > 1 else 0:.3f} "
                         f"({sum(c['ci'][0] > 0 for c in cs)}/{len(cs)})")
        w(f"| {design} | " + " | ".join(cells) + " |")
    w("")

    # Per-seed test AUROC of every row (primary design).
    res = {s: runs[s]["designs"][primary] for s in seeds}
    w(f"## Per-seed test macro AUROC ({primary}; [95% CI] over that seed's 41 test patients)\n")
    w("| Configuration | " + " | ".join(f"Seed {s}" for s in seeds) + " |")
    w("| --- | " + " | ".join("---" for _ in seeds) + " |")
    for row in TABLE_ROWS + ["no_meta"]:
        w(f"| {NAMES[row]} | " + " | ".join(ci(res[s]["rows"][row]["test"], "macro_auroc") for s in seeds) + " |")
    w("| Row 5, original (mean pooling + logistic) | " +
      " | ".join(ci(runs[s]["baselines"]["best_single_plus_metadata"]["test"], "macro_auroc") for s in seeds) + " |")
    w("")

    # Per-class AUROC and confusion matrix (primary design).
    w(f"## Per-class test AUROC ({primary}, mean over seeds)\n")
    w("Each test set holds 3–9 patients per class (Cribriform 3, Lepidic 4), so per-class values are noisy.\n")
    w("| Row | " + " | ".join(CLASSES) + " |")
    w("| --- | " + " | ".join("---" for _ in CLASSES) + " |")
    for row in ["fused", "no_meta", "uni2h", "virchow2", "genbio_pathfm", "best_plus_meta"]:
        vals = [np.mean([res[s]["rows"][row]["test"]["per_class_auroc"][c] for s in seeds]) for c in CLASSES]
        w(f"| {NAMES[row].replace('**', '')} | " + " | ".join(f"{v:.3f}" for v in vals) + " |")
    vals = [np.mean([runs[s]["baselines"]["best_single_plus_metadata"]["test"]["per_class_auroc"][c] for s in seeds])
            for c in CLASSES]
    w("| Row 5 (original: mean pooling + logistic) | " + " | ".join(f"{v:.3f}" for v in vals) + " |")
    w("")
    cm = np.sum([np.array(res[s]["rows"]["fused"]["test"]["confusion"]) for s in seeds], axis=0)
    w(f"## Confusion matrix ({primary} fused, test, summed over seeds {', '.join(map(str, seeds))})\n")
    w("Rows: true class; columns: predicted class (argmax). Per-class recall in the last column.\n")
    w("| True \\ Predicted | " + " | ".join(CLASSES) + " | Recall |")
    w("| --- | " + " | ".join("---" for _ in CLASSES) + " | --- |")
    for i, c in enumerate(CLASSES):
        w(f"| {c} | " + " | ".join(str(int(v)) for v in cm[i]) + f" | {cm[i, i] / max(cm[i].sum(), 1):.2f} |")
    if 0 in res:
        cm0 = np.array(res[0]["rows"]["fused"]["test"]["confusion"])
        w(f"\nSeed 0 alone (41 patients): diagonal {int(np.trace(cm0))}/41 correct; rows "
          + "; ".join(f"{c} {int(cm0[i, i])}/{int(cm0[i].sum())}" for i, c in enumerate(CLASSES)) + ".")
    w("")

    # Development vs test, metadata, sensitivity.
    w("## Development vs test (selection optimism)\n")
    w("| Design | Dev AUROC (mean ± sd) | Test AUROC (mean ± sd) | Test − dev (mean) | Seed 0: dev → test |")
    w("| --- | --- | --- | --- | --- |")
    for design in fcfg["designs"]:
        r = {s: runs[s]["designs"][design]["rows"]["fused"] for s in seeds}
        dv = [r[s]["dev"]["macro_auroc"]["estimate"] for s in seeds]
        tv = [r[s]["test"]["macro_auroc"]["estimate"] for s in seeds]
        s0 = f"{dv[seeds.index(0)]:.3f} → {tv[seeds.index(0)]:.3f}" if 0 in seeds else "–"
        w(f"| {design} | {ms(dv)} | {ms(tv)} | {np.mean(np.array(tv) - np.array(dv)):+.3f} | {s0} |")
    w("")
    w("## D11 sensitivity: test without the five patients with conflicting labels\n")
    w("| Design | Seeds with any of them in test | Test AUROC, all (mean) | Test AUROC, without them (mean) | "
      "Test bal. acc., all | Test bal. acc., without |")
    w("| --- | --- | --- | --- | --- | --- |")
    for design in fcfg["designs"]:
        r = {s: runs[s]["designs"][design]["rows"]["fused"] for s in seeds}
        n_with = sum(bool(runs[s]["conflicting_in_test"]) for s in seeds)
        w(f"| {design} | {n_with}/{len(seeds)} ("
          + ", ".join(f"s{s}: {len(runs[s]['conflicting_in_test'])}" for s in seeds) + ") | "
          f"{np.mean([r[s]['test']['macro_auroc']['estimate'] for s in seeds]):.3f} | "
          f"{np.mean([r[s]['test_without_conflicting']['macro_auroc'] for s in seeds]):.3f} | "
          f"{np.mean([r[s]['test']['balanced_accuracy']['estimate'] for s in seeds]):.3f} | "
          f"{np.mean([r[s]['test_without_conflicting']['balanced_accuracy'] for s in seeds]):.3f} |")
    w("")

    args.out.write_text("\n".join(L) + "\n")
    pd.DataFrame(rows_csv).to_csv(args.dir / "summary.csv", index=False)
    print(f"-> {args.out}, {args.dir / 'summary.csv'}")


if __name__ == "__main__":
    main()
